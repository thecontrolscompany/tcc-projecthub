create or replace function public.reserve_project_change_order_number(
  p_project_id uuid,
  p_prefix text default 'COR',
  p_padding integer default 4
)
returns table(sequence_number integer, cor_number text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sequence integer;
  v_prefix text := coalesce(nullif(btrim(p_prefix), ''), 'COR');
  v_padding integer := greatest(coalesce(p_padding, 4), 2);
begin
  insert into public.project_change_order_sequences (project_id, next_sequence)
  values (p_project_id, 1)
  on conflict (project_id) do nothing;

  update public.project_change_order_sequences
     set next_sequence = next_sequence + 1
   where project_id = p_project_id
   returning next_sequence - 1 into v_sequence;

  sequence_number := v_sequence;
  cor_number := v_prefix || '-' || lpad(v_sequence::text, v_padding, '0');
  return next;
end;
$$;

