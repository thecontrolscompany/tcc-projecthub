create or replace function public.normalize_change_order_status(input_status text)
returns co_status
language plpgsql
immutable
as $$
begin
  case lower(coalesce(btrim(input_status), 'draft'))
    when 'pending' then return 'in_review'::co_status;
    when 'needs_revision' then return 'needs_pricing'::co_status;
    when 'approved_po' then return 'approved'::co_status;
    when 'approved_email' then return 'approved'::co_status;
    when 'void' then return 'voided'::co_status;
    when 'draft' then return 'draft'::co_status;
    when 'needs_pricing' then return 'needs_pricing'::co_status;
    when 'ready_to_submit' then return 'ready_to_submit'::co_status;
    when 'submitted' then return 'submitted'::co_status;
    when 'in_review' then return 'in_review'::co_status;
    when 'approved' then return 'approved'::co_status;
    when 'rejected' then return 'rejected'::co_status;
    when 'voided' then return 'voided'::co_status;
    when 'superseded' then return 'superseded'::co_status;
    when 'executed' then return 'executed'::co_status;
    when 'billed' then return 'billed'::co_status;
    when 'paid' then return 'paid'::co_status;
    else return 'draft'::co_status;
  end case;
end;
$$;

create or replace function public.normalize_change_orders_v1()
returns trigger
language plpgsql
as $$
declare
  v_reserved record;
  v_effective_amount numeric(12,2);
begin
  new.status := public.normalize_change_order_status(coalesce(new.status::text, 'draft'));

  if tg_op = 'INSERT' then
    if new.sequence_number is null or new.cor_number is null or btrim(coalesce(new.cor_number, '')) = '' then
      select * into v_reserved
      from public.reserve_project_change_order_number(
        new.project_id,
        coalesce(nullif(btrim(new.number_prefix), ''), 'COR'),
        coalesce(new.number_padding, 4)
      )
      limit 1;

      new.sequence_number := v_reserved.sequence_number;
      new.cor_number := v_reserved.cor_number;
    end if;
  end if;

  if btrim(coalesce(new.co_number, '')) = '' then
    new.co_number := new.cor_number;
  end if;

  if new.number_prefix is null or btrim(new.number_prefix) = '' then
    new.number_prefix := 'COR';
  end if;

  if new.number_padding is null or new.number_padding < 2 then
    new.number_padding := 4;
  end if;

  v_effective_amount := coalesce(nullif(new.requested_amount, 0), new.amount, 0);
  new.requested_amount := v_effective_amount;
  new.amount := v_effective_amount;

  if new.status::text = 'submitted' and new.submitted_at is null then
    new.submitted_at := now();
  end if;

  if new.status::text = 'approved' and new.approved_at is null then
    new.approved_at := now();
  end if;

  if new.status::text = 'executed' and new.executed_at is null then
    new.executed_at := now();
  end if;

  if new.status::text = 'billed' and new.billed_at is null then
    new.billed_at := now();
  end if;

  if new.status::text = 'paid' and new.paid_at is null then
    new.paid_at := now();
  end if;

  if new.status::text = 'voided' and new.voided_at is null then
    new.voided_at := now();
  end if;

  if new.status::text = 'rejected' and new.rejected_at is null then
    new.rejected_at := now();
  end if;

  if new.status::text = 'superseded' and new.superseded_at is null then
    new.superseded_at := now();
  end if;

  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.recalculate_change_order_totals(p_change_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_requested_amount numeric(12,2);
  v_labor_amount numeric(12,2);
  v_material_amount numeric(12,2);
  v_equipment_amount numeric(12,2);
  v_subcontractor_amount numeric(12,2);
  v_other_amount numeric(12,2);
begin
  select
    coalesce(sum(total), 0)::numeric(12,2),
    coalesce(sum(total) filter (where category = 'labor'), 0)::numeric(12,2),
    coalesce(sum(total) filter (where category = 'material'), 0)::numeric(12,2),
    coalesce(sum(total) filter (where category = 'equipment'), 0)::numeric(12,2),
    coalesce(sum(total) filter (where category = 'subcontractor'), 0)::numeric(12,2),
    coalesce(sum(total) filter (where category = 'other'), 0)::numeric(12,2)
  into
    v_requested_amount,
    v_labor_amount,
    v_material_amount,
    v_equipment_amount,
    v_subcontractor_amount,
    v_other_amount
  from public.change_order_line_items
  where change_order_id = p_change_order_id;

  update public.change_orders
     set requested_amount = v_requested_amount,
         amount = v_requested_amount,
         labor_amount = v_labor_amount,
         material_amount = v_material_amount,
         equipment_amount = v_equipment_amount,
         subcontractor_amount = v_subcontractor_amount,
         other_amount = v_other_amount,
         updated_at = now()
   where id = p_change_order_id;
end;
$$;

create or replace function public.normalize_change_order_line_item()
returns trigger
language plpgsql
as $$
declare
  v_base numeric(12,2);
  v_markup numeric(12,2);
begin
  if new.category not in ('labor', 'material', 'equipment', 'subcontractor', 'other') then
    raise exception 'Invalid change order line item category: %', new.category;
  end if;

  v_markup := coalesce(new.markup_percent, 0);

  if new.category = 'labor' then
    v_base := coalesce(new.people_count, 0) * coalesce(new.hours_per_person, 0) * coalesce(new.days, 0) * coalesce(new.hourly_rate, 0);
  elsif new.lump_sum is not null then
    v_base := coalesce(new.lump_sum, 0);
  else
    v_base := coalesce(new.quantity, 0) * coalesce(new.unit_cost, 0);
  end if;

  new.base_amount := round(v_base::numeric, 2);
  new.total := round((v_base * (1 + (v_markup / 100)))::numeric, 2);
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.recalculate_change_order_totals_trigger()
returns trigger
language plpgsql
as $$
declare
  v_change_order_id uuid;
begin
  if tg_op = 'DELETE' then
    v_change_order_id := old.change_order_id;
  else
    v_change_order_id := new.change_order_id;
  end if;

  perform public.recalculate_change_order_totals(v_change_order_id);
  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

