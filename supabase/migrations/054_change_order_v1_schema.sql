create or replace function public.log_change_order_status_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.change_order_status_history (
      change_order_id,
      previous_status,
      new_status,
      reason,
      changed_by,
      changed_at,
      metadata
    )
    values (
      new.id,
      null,
      new.status,
      new.status_reason,
      new.modified_by,
      now(),
      jsonb_build_object('event', 'insert')
    );
    return new;
  end if;

  if old.status is distinct from new.status then
    insert into public.change_order_status_history (
      change_order_id,
      previous_status,
      new_status,
      reason,
      changed_by,
      changed_at,
      metadata
    )
    values (
      new.id,
      old.status,
      new.status,
      new.status_reason,
      new.modified_by,
      now(),
      jsonb_build_object(
        'event', 'status_change',
        'old_status_reason', old.status_reason,
        'new_status_reason', new.status_reason
      )
    );
  end if;

  return new;
end;
$$;

with ranked as (
  select
    id,
    project_id,
    row_number() over (
      partition by project_id
      order by created_at asc, id asc
    ) as rn
  from public.change_orders
)
update public.change_orders co
   set sequence_number = coalesce(co.sequence_number, ranked.rn),
       cor_number = coalesce(
         nullif(btrim(co.cor_number), ''),
         coalesce(
           case
             when co.sequence_number is not null then co.number_prefix || '-' || lpad(co.sequence_number::text, coalesce(co.number_padding, 4), '0')
             else null
           end,
           co.number_prefix || '-' || lpad(ranked.rn::text, coalesce(co.number_padding, 4), '0')
         )
       ),
       co_number = coalesce(nullif(btrim(co.co_number), ''), coalesce(nullif(btrim(co.cor_number), ''), co.number_prefix || '-' || lpad(ranked.rn::text, coalesce(co.number_padding, 4), '0')))
  from ranked
 where co.id = ranked.id
   and (
     co.sequence_number is null
     or co.cor_number is null
     or btrim(co.cor_number) = ''
     or co.co_number is null
     or btrim(co.co_number) = ''
   );

insert into public.project_change_order_sequences (project_id, next_sequence)
select
  project_id,
  greatest(coalesce(max(sequence_number), 0) + 1, 1)
from public.change_orders
group by project_id
on conflict (project_id) do update
set next_sequence = greatest(public.project_change_order_sequences.next_sequence, excluded.next_sequence),
    updated_at = now();

update public.change_orders
   set status = public.normalize_change_order_status(status::text),
       updated_at = now()
 where status::text in ('pending', 'needs_revision', 'approved_po', 'approved_email', 'void');

update public.change_orders
   set requested_amount = coalesce(nullif(requested_amount, 0), amount, 0),
       amount = coalesce(nullif(requested_amount, 0), amount, 0),
       co_number = coalesce(nullif(btrim(co_number), ''), cor_number),
       updated_at = now()
 where true;

